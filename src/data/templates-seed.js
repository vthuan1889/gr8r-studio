/* Which archetype owns a route. Unknown routes keep the current app. */
const PM_EXTRA = ['project', 'member', 'team', 'favorites', 'notifications', 'search'];
export function appOfRoute(route) {
  if (/^an-/.test(route)) return 'analytics';
  if (/^crm-/.test(route)) return 'crm';
  if (/^st-/.test(route)) return 'studio';
  if (/^cm-/.test(route)) return 'commerce';
  if (route === 'fl-hub') return 'flows';
  if (PM_EXTRA.includes(route)) return 'pm';
  const a = ARCHETYPES.find(x => x.routes.includes(route));
  return a ? a.id : null;
}

